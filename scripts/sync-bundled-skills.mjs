#!/usr/bin/env node
/**
 * Generate the bundled skill copies in @grafana/design-catalog from hatch sources.
 *
 * A handful of skills exist in two places:
 *   - `.hatch/_skills/<name>/SKILL.md` — the single source of truth, which
 *     `hatch gen` turns into the in-repo `/<name>` slash command (`.claude/`,
 *     `.agents/`, …).
 *   - `packages/design-catalog/skills/<name>/SKILL.md` — the published copy,
 *     which `@grafana/design-mcp` surfaces (`list_design_skills`,
 *     `get_design_skill`, `search`) and `design-codemods install-skill` copies
 *     into a consumer repo. This is the only way a skill reaches a repo that
 *     merely installs the MCP server / CLI, with no `.hatch/` of its own.
 *
 * Both build-guidance skills (e.g. `design`) and codemod skills bundle into the
 * catalog. This script keeps each published copy in lockstep with its hatch
 * source: the body is copied verbatim and the frontmatter is rewritten to the
 * minimal `name` + `description` shape the bundled-skill readers expect
 * (design-mcp only parses `description:`). It runs as part of `pnpm hatch:gen`,
 * so the `hatch.yml` CI gate (`hatch:gen` + `git status --porcelain`) fails if a
 * published copy ever drifts from the source. Do not hand-edit the generated
 * files — edit the `.hatch` source and re-run `pnpm hatch:gen`.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);

/**
 * Skills bundled into `@grafana/design-catalog` from a hatch source. Each
 * `name` maps `.hatch/_skills/<name>/SKILL.md` to
 * `packages/design-catalog/skills/<name>/SKILL.md`.
 */
const BUNDLED_SKILLS = [];

/** Split a SKILL.md into its YAML frontmatter lines and body. */
function parseSkill(raw, src) {
  const lines = raw.split('\n');
  if (lines[0] !== '---') {
    throw new Error(`${src}: expected YAML frontmatter starting with '---'`);
  }
  const close = lines.indexOf('---', 1);
  if (close === -1) {
    throw new Error(`${src}: unterminated YAML frontmatter`);
  }
  const frontmatter = lines.slice(1, close);
  const body = lines.slice(close + 1);
  // Drop leading blank lines so the body starts at its first heading.
  while (body.length > 0 && body[0].trim() === '') body.shift();
  return { frontmatter, body: body.join('\n') };
}

/** Read a single-line scalar field out of frontmatter lines. */
function field(frontmatter, key, src) {
  const prefix = `${key}:`;
  const line = frontmatter.find((l) => l.startsWith(prefix));
  if (!line) throw new Error(`${src}: missing '${key}:' in frontmatter`);
  return line.slice(prefix.length).trim();
}

let wrote = 0;

for (const name of BUNDLED_SKILLS) {
  const srcPath = path.join(repoRoot, '.hatch', '_skills', name, 'SKILL.md');
  const destPath = path.join(
    repoRoot,
    'packages',
    'design-catalog',
    'skills',
    name,
    'SKILL.md',
  );

  const raw = fs.readFileSync(srcPath, 'utf8');
  const { frontmatter, body } = parseSkill(raw, srcPath);
  const description = field(frontmatter, 'description', srcPath);

  const output =
    [
      '---',
      `# Generated from .hatch/_skills/${name}/SKILL.md by scripts/sync-bundled-skills.mjs.`,
      '# Edit the .hatch source and run `pnpm hatch:gen`; do not edit this file by hand.',
      `name: ${name}`,
      `description: ${description}`,
      '---',
      '',
      body.replace(/\s+$/, ''),
    ].join('\n') + '\n';

  fs.mkdirSync(path.dirname(destPath), { recursive: true });
  const existing = fs.existsSync(destPath)
    ? fs.readFileSync(destPath, 'utf8')
    : null;
  if (existing !== output) {
    fs.writeFileSync(destPath, output);
    wrote += 1;
    process.stderr.write(
      `synced ${path.relative(repoRoot, destPath)} from .hatch/_skills/${name}/SKILL.md\n`,
    );
  }
}

process.stderr.write(
  `sync-bundled-skills: ${BUNDLED_SKILLS.length} skill(s) checked, ${wrote} written.\n`,
);
